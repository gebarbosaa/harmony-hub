-- Normalize payment/account/card references and reject cross-household references.
create or replace function private.normalize_accounts_payable() returns trigger
language plpgsql security definer set search_path='public,pg_catalog' as $$
declare
  p public.household_payment_methods%rowtype;
begin
  if new.payment_method_id is not null then
    select * into p from public.household_payment_methods
      where id = new.payment_method_id and household_id = new.household_id;
    if p.id is null then
      raise exception 'FORMA DE PAGAMENTO INVÁLIDA PARA ESTA CASA';
    end if;
    new.card_id := p.card_id;
    if new.account_id is null then new.account_id := p.account_id; end if;
  end if;

  if new.account_id is not null and not exists (
    select 1 from public.household_accounts a
      where a.id = new.account_id and a.household_id = new.household_id
  ) then
    raise exception 'CONTA/BANCO INVÁLIDO PARA ESTA CASA';
  end if;

  if new.card_id is not null and not exists (
    select 1 from public.cards c
      where c.id = new.card_id and c.household_id = new.household_id
  ) then
    raise exception 'CARTÃO INVÁLIDO PARA ESTA CASA';
  end if;

  if new.payment_method_id is not null and p.kind = 'CREDITO' and new.card_id is null then
    raise exception 'FORMA DE CRÉDITO PRECISA DE CARTÃO';
  end if;

  return new;
end;
$$;
drop trigger if exists trg_normalize_accounts_payable on public.accounts_payable;
create trigger trg_normalize_accounts_payable
before insert or update on public.accounts_payable
for each row execute function private.normalize_accounts_payable();

-- A paid payable creates exactly one ledger transaction. Reopening/removing it
-- removes only the transaction generated by this payable.
create or replace function private.sync_accounts_payable_transaction() returns trigger
language plpgsql security definer set search_path='public,pg_catalog' as $$
declare
  v_tx uuid;
  v_date date;
begin
  if tg_op in ('UPDATE','DELETE') and old.linked_transaction_id is not null then
    if tg_op = 'DELETE' or new.status <> 'PAGA' then
      delete from public.transactions
        where id = old.linked_transaction_id
          and household_id = old.household_id
          and source_type = 'ACCOUNTS_PAYABLE'
          and source_id = old.id;
      if tg_op <> 'DELETE' then new.linked_transaction_id := null; end if;
    end if;
  end if;

  if tg_op = 'DELETE' then return old; end if;
  if new.status <> 'PAGA' then return new; end if;

  v_date := coalesce(new.paid_at::date, new.due_date, current_date);

  if new.linked_transaction_id is not null then
    update public.transactions set
      date=v_date, description=new.description, amount=new.amount,
      category=new.category, responsible=new.responsible, paid=true,
      payment_method_id=new.payment_method_id, card_id=new.card_id,
      account_id=new.account_id, payment_method_name=(select hpm.name from public.household_payment_methods hpm where hpm.id=new.payment_method_id),
      pay_method=coalesce((select hpm.kind from public.household_payment_methods hpm where hpm.id=new.payment_method_id), pay_method),
      card_name=(select c.name from public.cards c where c.id=new.card_id),
      updated_at=now()
    where id=new.linked_transaction_id and household_id=new.household_id and source_type='ACCOUNTS_PAYABLE' and source_id=new.id;
    if found then return new; end if;
    new.linked_transaction_id := null;
  end if;

  insert into public.transactions(
    household_id,date,description,amount,type,category,pay_method,card_name,responsible,
    paid,payment_method_name,payment_method_id,card_id,account_id,source_type,source_id,source_index,source_total,source_period
  ) values (
    new.household_id,v_date,new.description,new.amount,'DESPESA',new.category,
    coalesce((select hpm.kind from public.household_payment_methods hpm where hpm.id=new.payment_method_id),'BOLETO'),
    (select c.name from public.cards c where c.id=new.card_id),new.responsible,true,
    (select hpm.name from public.household_payment_methods hpm where hpm.id=new.payment_method_id),
    new.payment_method_id,new.card_id,new.account_id,'ACCOUNTS_PAYABLE',new.id,1,1,to_char(v_date,'YYYY-MM')
  ) returning id into v_tx;
  new.linked_transaction_id := v_tx;
  return new;
end;
$$;
drop trigger if exists trg_sync_accounts_payable_transaction on public.accounts_payable;
create trigger trg_sync_accounts_payable_transaction
after insert or update or delete on public.accounts_payable
for each row execute function private.sync_accounts_payable_transaction();

-- Protect the financial ledger from cross-household foreign references.
create or replace function private.validate_transaction_household_refs() returns trigger
language plpgsql security definer set search_path='public,pg_catalog' as $$
begin
  if new.payment_method_id is not null and not exists (
    select 1 from public.household_payment_methods p where p.id=new.payment_method_id and p.household_id=new.household_id
  ) then raise exception 'FORMA DE PAGAMENTO INVÁLIDA PARA ESTA CASA'; end if;
  if new.account_id is not null and not exists (
    select 1 from public.household_accounts a where a.id=new.account_id and a.household_id=new.household_id
  ) then raise exception 'CONTA/BANCO INVÁLIDO PARA ESTA CASA'; end if;
  if new.card_id is not null and not exists (
    select 1 from public.cards c where c.id=new.card_id and c.household_id=new.household_id
  ) then raise exception 'CARTÃO INVÁLIDO PARA ESTA CASA'; end if;
  return new;
end;
$$;
drop trigger if exists trg_validate_transaction_household_refs on public.transactions;
create trigger trg_validate_transaction_household_refs
before insert or update on public.transactions
for each row execute function private.validate_transaction_household_refs();

